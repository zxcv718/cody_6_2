"""프롬프트 계층 — AI에게 '부탁'하는 곳.

이 모듈이 만드는 것은 전부 확률적이다. "제목 50자 이내로 써줘"라고 써도 지켜진다는
보장은 없다. 보장이 필요한 규칙은 formatter.py가 코드로 강제한다.

두 계층을 나눈 이유: 안 나누면 "왜 가끔 72자를 넘지?"를 만났을 때 프롬프트를 고칠지
후처리를 고칠지 판단할 지점이 없다.

────────────────────────────────────────────────────────────────────────────
출력 계약 (formatter.py가 이 형식을 파싱한다 — 바꾸려면 양쪽을 같이 바꿔야 한다)

  commit:  첫 줄 = 제목
           빈 줄
           나머지 = 본문 (`- ` 불릿)

  pr:      <<<TITLE>>>
           한 줄 제목
           <<<BODY>>>
           ## Why
           - ...
           ## What
           - ...
           ## How to Test
           - ...
────────────────────────────────────────────────────────────────────────────
"""

from __future__ import annotations

from gitctx import GitContext
from sanitizer import SanitizeResult

PR_TITLE_MARKER = "<<<TITLE>>>"
PR_BODY_MARKER = "<<<BODY>>>"
PR_SECTIONS = ("Why", "What", "How to Test")


# ─────────────────────────────────────────────────────────────────────────────
# 시스템 프롬프트
#
# 과제 명세는 출력 언어를 규정하지 않는다(`evLang: null`, 본문에 언급 없음).
# 다만 결과 예시(8절)가 전부 한국어 + `feat:` 접두사이므로 그에 맞췄다.
#
# ⚠️ 섹션 헤더 `## Why` / `## What` / `## How to Test`는 **영어가 강제**다
#    (기능 요구사항 4번에 명시). 여기만은 번역하면 안 된다.
#
# 설계 원칙
#   - 명시하지 않은 것은 "알아서 잘"이 아니라 "매번 다르게"가 된다.
#     실제로 언어를 안 적었을 때 커밋은 영어, PR 본문은 한국어로 갈렸다.
#   - 형식 규칙(길이·섹션)은 여기서 *부탁*하고 formatter.py가 *강제*한다.
#     프롬프트에도 적는 이유는, 애초에 지켜져 나오면 후처리로 깎을 일이 없어
#     결과가 더 자연스럽기 때문이다. 이중 방어이지 중복이 아니다.
#   - 환각 억제 지시("diff에 없는 내용을 쓰지 마라")를 넣었다. 특히 `## Why`는
#     변경 *이유*를 묻는데 그건 diff에 적혀 있지 않아 모델이 지어내기 쉽다.
# ─────────────────────────────────────────────────────────────────────────────

