# ─────────────────────────────────────────────────────────────────────────────
# 아래부터는 사용자 프롬프트(=재료) 조립. 여기는 고칠 일이 거의 없다.
# ─────────────────────────────────────────────────────────────────────────────


def _context_block(ctx: GitContext, sanitized: SanitizeResult) -> str:
    """AI에게 넘길 재료를 '요약 → 상세' 순서로 쌓는다.

    파일 목록을 diff보다 먼저 두는 이유: diff는 길고 노이즈가 많다. 전체 그림을 먼저
    주면 모델이 개별 헌크를 읽을 때 맥락을 갖고 읽는다.
    """
    lines = [
        f"현재 브랜치: {ctx.branch}",
        f"변경 규모: 파일 {len(ctx.files)}개, +{ctx.added_lines}줄 / -{ctx.removed_lines}줄",
    ]
    if not ctx.has_commits:
        # 최초 커밋은 "무엇을 바꿨나"가 아니라 "무엇을 만들었나"다. 맥락을 알려주지
        # 않으면 AI가 존재하지도 않는 이전 상태와의 차이를 지어낸다.
        lines.append("참고: 이 저장소에는 아직 커밋이 없습니다. 이번이 최초 커밋입니다.")
    lines += [
        "",
        "## 변경된 파일",
        ctx.file_summary() or "(없음)",
    ]

    notes = sanitized.report_lines()
    if notes:
        # 마스킹·절단 사실을 AI에게도 알린다. 모르면 "[MASKED_API_KEY]라는 값을
        # 추가했다"처럼 자리표시자를 진짜 변경 내용으로 착각해 요약한다.
        lines += [
            "",
            "## 참고 (전송 전 처리됨)",
            *[f"- {n}" for n in notes],
            "- 위 처리로 일부 내용이 가려지거나 생략되었습니다. "
            "가려진 자리표시자 자체를 변경 내용으로 서술하지 마세요.",
        ]

    lines += ["", "## 변경 내용 (git diff)", "```diff", sanitized.text or "(diff 없음)", "```"]
    return "\n".join(lines)


def build_commit_user(ctx: GitContext, sanitized: SanitizeResult) -> str:
    return _context_block(ctx, sanitized) + "\n\n위 변경 사항에 대한 커밋 메시지를 작성하세요."


def build_pr_user(ctx: GitContext, sanitized: SanitizeResult) -> str:
    return _context_block(ctx, sanitized) + "\n\n위 변경 사항에 대한 PR 제목과 본문을 작성하세요."


def retry_hint(issues: list[str]) -> str:
    """재생성 2회차에 덧붙이는 지시. 무엇이 왜 잘못됐는지 구체적으로 알려준다."""
    bullets = "\n".join(f"- {i}" for i in issues)
    return (
        "\n\n[재작성 요청] 직전 응답이 아래 규칙을 어겼습니다. "
        "같은 내용을 형식만 고쳐 다시 출력하세요.\n" + bullets
    )
